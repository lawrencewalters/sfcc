#!/bin/bash -ex

# create content and catalog for sandbox from staging data

source "$(dirname "$0")/paths.env"

# $1: output folder
# $2: site id
# $3: site catalog id
# $4: content library id
# $5: master catalog id
# $6: clubs catalog id (optional)

# Validate that 1 command-line parameters are provided
if [ "$#" -lt 5 ]; then
    echo "Usage: $0 <output_folder> <site_id> <site_catalog_id> <content_library_id> <master_catalog_id> [<clubs_catalog_id>]"
    exit 1
fi

# Trim $1 at the first special character (: or |)
dir_name="${1%%[:|]*}"

mkdir -p "$TMP_DIR/$dir_name"
mkdir -p "$TMP_DIR/$dir_name/sites"
mkdir -p "$TMP_DIR/$dir_name/sites/$2"
mkdir -p "$TMP_DIR/$dir_name/libraries"
mkdir -p "$TMP_DIR/$dir_name/libraries/$4"

# get online categories: 
	# input: storefront catalog from staging
	# output: file with categoryIds pipe separated for use in next XSLT

java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/catalogs/$3/catalog.xml" -xsl:"$SCRIPT_DIR/get-online-categories.xslt" > "$SCRIPT_DIR/data/categoryIds.txt"

# generate trimmed slots
	# input: staging site slots.xml, file with online category ids (optional)
	# output: sandbox appropriate slots.xml

cat "$SCRIPT_DIR/data/categoryIds.txt" | xargs -t java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/sites/$2/slots.xml" -xsl:"$SCRIPT_DIR/generate-trimmed-slots.xslt" > "$TMP_DIR/$dir_name/sites/$2/slots.xml"

# get the content asset IDs referenced in the new slots
    # input: new slots.xml, file with online category ids (optional)
    # output: pipe separated list of content asset ids

cat "$SCRIPT_DIR/data/categoryIds.txt" | xargs -t java -jar "$SAXON_JAR" -s:"$TMP_DIR/$dir_name/sites/$2/slots.xml" -xsl:"$SCRIPT_DIR/get-content-ids-from-slots.xslt" > data/contentIds.txt

# get the content asset IDs referenced in code
find /home/lwalters/bitbucket.org/lyonsconsultinggroup/acushnet -name "*.isml" -type f -exec grep -o 'aid="[^"]*"' {} \; | sed 's/aid="//g' | sed 's/"//g' | sort | uniq | grep '^[a-z]' | paste -sd'|' - >> data/contentIds.txt

# TODO: get the content ids referenced by product custom attributes or other places?

# generate trimmed library
    # input: staging library.xml, file with list of contentIds to retrieve
    # output: trimmed content library

# Clean the source XML first to remove invalid characters
"$SCRIPT_DIR/clean-xml.sh" "$TMP_DIR/$SOURCE_DIR/libraries/$4/library.xml" "$TMP_DIR/$SOURCE_DIR/libraries/$4/library-clean.xml"

cat "$SCRIPT_DIR/data/contentIds.txt" | xargs -t java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/libraries/$4/library-clean.xml" -xsl:"$SCRIPT_DIR/generate-trimmed-content-library.xslt" > "$TMP_DIR/$dir_name/libraries/$4/library.xml"

# get a map of product urls to product id (titleist hardcodes paths in their content assets, that don't work well in sandboxes)
    # input: master catalog
    # output: text file with page-url:product-id entries, 1 per line

java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/catalogs/$5/catalog.xml" -xsl:"$SCRIPT_DIR/get-product-url-mappings.xslt" > "$SCRIPT_DIR/data/url-to-product-id-mapping.txt"

# do it again for clubs catalog
if [ -n "$6" ]; then
    java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/catalogs/$6/catalog.xml" -xsl:"$SCRIPT_DIR/get-product-url-mappings.xslt" >> "$SCRIPT_DIR/data/url-to-product-id-mapping.txt"
fi

# post-process the content library to fix URLs to be generated by SFCC and not hardcoded
    # input: trimmed content library, map of product urls to product id in file data/url-to-product-id-mapping.txt
    # output: trimmed content library updated in place

./update-content-urls-with-product-ids.sh "$TMP_DIR/$dir_name/libraries/$4/library.xml"

# get a map of page-url to category id (titleist hardcodes paths in their content assets, that don't work well in sandboxes)
    # input: staging site catalog
    # output: text file with page-url:category-id entries, 1 per line

java -jar "$SAXON_JAR" -s:"$TMP_DIR/$SOURCE_DIR/catalogs/$3/catalog.xml" -xsl:"$SCRIPT_DIR/get-category-url-mappings.xslt" > "$SCRIPT_DIR/data/url-to-category-id-mapping.txt"

# post-process the content library to fix URLs to be generated by SFCC and not hardcoded
    # input: trimmed content library, map of category:page-attributes:page-url to category id in file data/url-to-category-id-mapping.txt
    # output: trimmed content library updated in place

./update-content-urls-with-category-ids.sh "$TMP_DIR/$dir_name/libraries/$4/library.xml"

# post-process the content library to fix hostnames to sandbox urls
    # input: trimmed content library, map of production url hostname: sandbox hostname + site path in file data/url-to-sandbox-mapping.txt
    # output: trimmed content library updated in place

./update-content-site-urls.sh "$TMP_DIR/$dir_name/libraries/$4/library.xml"

npx b2c-tools import run "$TMP_DIR/$dir_name"